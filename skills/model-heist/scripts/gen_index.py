#!/usr/bin/env python3
"""Regenerate docs/INDEX.md from the document tree.

An index that omits a document is a lie the next session believes, so this runs
after every add/rename/archive. Deterministic output: same tree -> same bytes.

    python gen_index.py reverse/<target>
"""
from __future__ import annotations

import argparse
import os
import re
import sys

ROOT_DOCS = ("README.md",)
SKIP_DIRS = {".git", "node_modules", "artifacts", "state"}
H1 = re.compile(r"^#\s+(.+?)\s*$", re.M)


def title_of(path: str) -> str:
    try:
        with open(path, "r", encoding="utf-8", errors="replace") as fh:
            head = fh.read(4000)
    except OSError:
        return ""
    m = H1.search(head)
    return m.group(1).strip() if m else ""


def main() -> int:
    ap = argparse.ArgumentParser(description="Regenerate docs/INDEX.md from the document tree.")
    ap.add_argument("root", nargs="?", default=".", help="campaign root (the directory holding docs/)")
    a = ap.parse_args()
    root = os.path.abspath(a.root)
    if not os.path.isdir(os.path.join(root, "docs")):
        print(f"no docs/ under {root}", file=sys.stderr)
        return 2

    rows: list[tuple[str, str]] = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS)
        for name in sorted(filenames):
            if not name.endswith(".md"):
                continue
            full = os.path.join(dirpath, name)
            rel = os.path.relpath(full, root).replace("\\", "/")
            if rel == "docs/INDEX.md":
                continue
            if rel in ROOT_DOCS:
                continue
            rows.append((rel, title_of(full) or "_(untitled)_"))

    rows.sort()
    findings = [r for r in rows if r[0].startswith("docs/findings/")]
    curated = [r for r in rows if r[0].startswith("docs/") and r not in findings]
    other = [r for r in rows if not r[0].startswith("docs/")]

    out = ["# INDEX", "",
           "_Generated by scripts/gen_index.py. Do not hand-edit._", ""]
    readme = os.path.join(root, "README.md")
    if os.path.exists(readme):
        out += ["## Entry", "", f"- [README.md]({'../README.md'}) — {title_of(readme)}", ""]

    for header, group in (("Protocol and state", curated),
                          ("Findings", findings),
                          ("Everything else", other)):
        if not group:
            continue
        out += [f"## {header}", "", "| document | title |", "|---|---|"]
        for rel, title in group:
            link = os.path.relpath(os.path.join(root, rel),
                                   os.path.join(root, "docs")).replace("\\", "/")
            out.append(f"| [{rel}]({link}) | {title} |")
        out.append("")

    out += [f"_{len(rows)} documents._", ""]
    target = os.path.join(root, "docs", "INDEX.md")
    with open(target, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(out))
    print(f"indexed {len(rows)} documents -> {target}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())